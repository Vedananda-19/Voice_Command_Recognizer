// Source: 02 Buffering and Framing - Memory and Handshakes.md
// Ring buffer (512) + hop counter (256) + windowed copy into the FFT input RAM.
module frame_buffer (
    input  wire               clk,
    input  wire               rst,
    input  wire signed [15:0] sample,
    input  wire               sample_valid,
    output reg                fft_we,
    output reg        [8:0]   fft_waddr,
    output reg signed [15:0]  fft_wdata,
    output reg                frame_done
);
    localparam N = 512, HOP = 256;

    // ---------- write side: ring buffer ----------
    reg signed [15:0] ring [0:N-1];
    reg        [8:0]  wptr;                 // 9 bits → wraps at 512 automatically
    reg        [7:0]  hop_cnt;              // 0..255 → wraps at 256 automatically
    reg        [9:0]  filled;               // saturates at 512

    wire hop_tick = sample_valid && (hop_cnt == HOP-1) && (filled >= N-1);

    always @(posedge clk) begin
        if (rst) begin
            wptr <= 0; hop_cnt <= 0; filled <= 0;
        end else if (sample_valid) begin
            wptr    <= wptr + 1'b1;
            hop_cnt <= hop_cnt + 1'b1;
            if (filled != N) filled <= filled + 1'b1;
        end
    end

    // ---------- window ROM ----------
    reg signed [15:0] win [0:N-1];
    initial $readmemh("hann512_q15.mem", win);   // generated by Python (note 07)

    // ---------- stage 0: copy controller ----------
    reg        busy;
    reg  [8:0] n;                           // frame index 0..511
    reg  [8:0] base;                        // address of the oldest sample
    wire [8:0] raddr = base + n;            // wraps mod 512 automatically

    always @(posedge clk) begin
        if (rst) begin
            busy <= 0; n <= 0;
        end else if (hop_tick && !busy) begin
            busy <= 1'b1;
            n    <= 0;
            base <= wptr + 1'b1;            // this edge writes ring[wptr]; oldest is next slot
        end else if (busy) begin
            n <= n + 1'b1;
            if (n == N-1) busy <= 1'b0;
        end
    end

    // ---------- stage 1: memory reads (1-cycle latency) ----------
    reg signed [15:0] x1, w1;
    reg        [8:0]  n1;
    reg               v1;
    always @(posedge clk) begin
        if (sample_valid) ring[wptr] <= sample;   // write port
        x1 <= ring[raddr];                        // read port
        w1 <= win[n];
        n1 <= n;
        v1 <= busy;
    end

    // ---------- stage 2: multiply ----------
    reg signed [31:0] prod;
    reg        [8:0]  n2;
    reg               v2;
    always @(posedge clk) begin
        prod <= x1 * w1;                          // Q0 × Q15 → Q15, 32-bit
        n2   <= n1;
        v2   <= v1;
    end

    // ---------- stage 3: rescale + write to FFT RAM ----------
    always @(posedge clk) begin
        fft_we     <= v2;
        fft_waddr  <= n2;
        fft_wdata  <= prod[30:15];                // = prod >>> 15, fits in 16 bits
        frame_done <= fft_we && (fft_waddr == N-1);  // one clock after the last write
    end
endmodule
